import { mkdirSync, writeFileSync } from "node:fs";
import aruco from "js-aruco2";
import { mockCompetition } from "../src/lib/mock.ts";

mkdirSync("public/cards", { recursive: true });
const dictionary = new aruco.AR.Dictionary("ARUCO_MIP_36h12");
for (let id = 0; id < 20; id++)
  writeFileSync(`public/cards/${id}.svg`, dictionary.generateSVG(id), "utf8");
const state = mockCompetition();
const initial = JSON.stringify(state).replaceAll("'", "''");
state.revision = 1;
const next = JSON.stringify(state).replaceAll("'", "''");
writeFileSync(
  "supabase/seed.sql",
  `-- Generated by node scripts/generate-assets.mjs. Fresh project only; never reset live votes.\n-- Sample names, scores and votes are fictional demo data. No access tokens are seeded.\nbegin;\ninsert into public.competitions(id, title, revision, state) values ('luodong-live', '羅東國中・卡拉之聲', 0, '${initial}'::jsonb);\nselect public.save_competition('luodong-live', 0, '${next}'::jsonb, '{"type":"seed","actor":"setup"}'::jsonb);\ncommit;\n`,
  "utf8",
);
